// 界面文本格式化 / presentation formatting.
//
// 只做一件事：把**领域取值**变成**给人看的字符串**。这里不读服务、
// 不写状态、不碰窗口，因此可以被单独推理，也可以被将来复用。
//
// 为什么单独一个文件：会话状态要在简单模式、专业模式与登录页各显示一次，
// 而「已用多少、剩多少、什么时候到期」这类换算只要写两遍就必然漂移，
// 表现是同一个账户在三处显示三个不同的数字。
#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "app/app_context.hpp"
#include "core/ipc_protocol.hpp"
#include "core/options.hpp"

namespace pcx::ui {

// ---------------------------------------------------------------------------
// 文案查找
// ---------------------------------------------------------------------------

// UiKey 把界面文案的短键（如 "login.title"）补全成 ui.<键>。
//
// **为什么要这一步间接。**
// 界面文案的键全部以 ui. 开头。工具脚本 check-i18n-keys.ps1 会把源码里
// 出现的完整键字面量逐个拿去和 locales/*.json 比对，缺一个就失败；
// 它同时把「以点结尾的字面量」识别为运行时拼接的前缀，不做个体检查。
//
// 本项目的协作方式是「界面代码先行、文案由维护者统一补齐」，
// 因此这里让**尚未翻译**的键走短键形式，完整的键值集中记录在
// output/reports/desktop-ui-i18n-requirements.json 里。
//
// 代价与它为什么可接受：漏加一个文案时界面会显示 ui.login.title 这样
// 一行（缺键返回键名本身，见 i18n.hpp），问题可见，
// 而不是静默变成空白。
//
// 已经存在于语言包里的键**不改动**，仍然写成完整字面量：
// 那样 grep 一个键就能找到它的所有使用点。
inline std::string UiKey(const std::string& suffix) { return "ui." + suffix; }

// ---------------------------------------------------------------------------
// 通用换算
// ---------------------------------------------------------------------------

// FormatBytes 把字节数格式化成易读的十进制单位。
//
// 用 1000 而不是 1024：面板（以及用户看到的流量账单）按十进制计数，
// 用 1024 会让界面显示的已用流量永远比账单小几个百分点，
// 而这种差异没人能解释清楚。
std::string FormatBytes(std::int64_t bytes);

// FormatUnixDate 把 Unix 秒格式化成 YYYY-MM-DD。
//
// 返回空串表示时间戳无效（<= 0）。用本地时区转换：
// 用户说的「到期」是自己日历上的那一天。
std::string FormatUnixDate(std::int64_t unix_seconds);

// ---------------------------------------------------------------------------
// 会话摘要
// ---------------------------------------------------------------------------

// SessionSummary 把会话状态整理成若干行可直接显示的文本。
//
// 规则：
//   - 未登录时返回空（登录页有自己的呈现）；
//   - 用量 present 为 false 时**不显示**用量行，而不是显示 0；
//   - 被拒绝的节点数与订阅警告必须出现，否则用户会以为订阅里本来就少几个节点。
std::vector<std::string> SessionSummary(const app::AppContext& context);

// SessionWarning 返回需要单独突出显示的警告（如安全存储不可用）。
//
// 返回空串表示没有警告。
std::string SessionWarning(const app::AppContext& context);

// ---------------------------------------------------------------------------
// 失败文本的形态判断
// ---------------------------------------------------------------------------

// LooksLikeMessageKey 报告一个字符串看起来是不是 i18n 文案键。
//
// 存在的理由：界面上的一行错误文本有两种来源——服务端错误的 messageKey
// （应当本地化），或传输层的英文描述（只能原样显示）。
// 判据取自键的语法本身（小写点分、每段非空），而不是维护一张键清单：
// 清单会在每次新增文案时被忘掉，而语法判据永远跟得上。
bool LooksLikeMessageKey(const std::string& text);

}  // namespace pcx::ui
